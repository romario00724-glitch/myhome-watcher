"""
Лише для Тбілісі: чи пише автор у описі, що НЕ співпрацює з рієлторами.

Рішення користувача 12.10.2026: група — для рієлторів, тож оголошення, де прямо написано
«с агентствами не сотрудничаю», «агентам не звонить», «риелторов просьба не беспокоить», не
надсилати. Але якщо в описі є хоч якась співпраця («сотрудничаю 50%», «С риелторами — 50/50»,
«возможно сотрудничество с агентами») — надсилати, навіть якщо поруч є «не звоните».
Нечіткі фрази відмовою не вважаються: «агенты, не копируйте объявление», «без комиссии»,
«без посредников», «я не плачу комиссию».

watcher.py викликає refuses_realtors() у run_once, якщо SKIP_NO_REALTORS = True.
Перевірено на 960 описах ss.ge (Тбілісі й Батумі) 12.10.2026.
"""

import re

# Рієлтори, агенти, агентства, посередники… (у т. ч. з помилкою «агенство»), англійською й грузинською
TARGET = (r"(?:риелтор|риэлтор|рієлтор|агент|агенс|агенц|посредни|маклер|брокер"
          r"|realtor|agent|agenc|broker|რიელტორ|აგენტ|სააგენტო|შუამავ|მაკლერ|ბროკერ)\w*")
GAP = r"(?:[\w'’-]+[\s,/:—–-]+){0,5}?"  # до п'яти слів між ними, але не через кінець речення
NOT = r"н[еи]\s+(?:(?:буду|готов\w*|хочу|хотим|планиру\w*)\s+)?"  # «не», «не буду», «не готов»
REFUSE_VERB = (r"(?:" + NOT + r"(?:сотрудн|работа|звон|беспок|пис|пиш|обращ|турб|отклик|связыва"
               r"|интерес|рассматр|предлаг|тревож|отвеча)\w*|нежелательн\w*|не\s+нужн[ыа]\b)")

REFUSAL = re.compile(
    TARGET + r"[\s,/:!—–-]+" + GAP + r"(?:просьба\s+|прошу\s+|пожалуйста[\s,]+)?" + REFUSE_VERB  # «Агентам не звонить»
    + r"|\b" + NOT + r"(?:сотрудн|работа|звон|беспок|пис|пиш|обращ|связыва)\w*[\s,]+"             # «не сотрудничаю с агентствами»,
    + r"(?:(?:мне\s+)?(?:с|со|из|от)\s+)?" + GAP + TARGET                                        # «не звоните из агентств»
    + r"|\b" + NOT + r"сотрудни\w*"                                                                # «Не сотрудничаю!»
    + r"|\b(?:don'?t|do\s+not|not|never|won'?t)\s+(?:work|cooperate|deal)\w*\s+with\s+" + GAP + TARGET
    + r"|" + TARGET + r"\W+" + GAP + r"(?:please\s+)?(?:don'?t|do\s+not|not)\s+(?:call|contact|disturb|bother|text|write)"
    + r"|\bno\s+(?:agents|realtors|agencies|brokers)\b(?!\s+(?:fee|commission))"
    + r"|(?:არ|ნუ)\s+(?:ვთანამშრომლ|ვითანამშრომლ|ვმუშა|ვიმუშავ)\S*"                               # «არ ვთანამშრომლობ»
    + r"|" + TARGET + r"\s+" + GAP + r"(?:არ|ნუ)\s+(?:დარეკ|შემაწუხ|შეაწუხ|მომწერ|დამირეკ)\S*",       # «მაკლერებმა არ დარეკოთ»
    re.IGNORECASE)

# Співпраця: дієслово без заперечення поруч із рієлтором — або відсотки/частки біля нього
COOPERATE_WORD = re.compile(r"сотрудни\w*|работаю\b|работаем\b|работает\b|cooperat\w*"
                            r"|(?<![\u10D0-\u10FF])ვ?ი?თანამშრომლ\S*",
                            re.IGNORECASE)
NEGATED = re.compile(r"(?:\b(?:не|ни|нет|без)|(?:არ|ნუ))\s+(?:(?:буду|готов\w*|хочу|хотим|планиру\w*)\s+)?$",
                     re.IGNORECASE)
NEGATED_AFTER = re.compile(r"^[^.!?\n]{0,40}?(?:\bне\s+(?:рассматр|интерес|предусм|возмож|нуж|практику)|невозмож|исключ)",
                           re.IGNORECASE)
NEAR_TARGET = re.compile(TARGET, re.IGNORECASE)
SHARE = r"(?:\d+\s*%|\d+\s*/\s*\d+|пополам|половин\w*)"
SHARE_NEAR_TARGET = re.compile(TARGET + r"[^.!?\n]{0,30}?" + SHARE + r"|" + SHARE + r"[^.!?\n]{0,30}?" + TARGET,
                               re.IGNORECASE)


def mentions_cooperation(text):
    """«сотрудничаю с агентствами», «С агентами сотрудничаю — 30%», «С риелторами — 50/50»."""
    if SHARE_NEAR_TARGET.search(text):
        return True
    for m in COOPERATE_WORD.finditer(text):
        if NEGATED.search(text[max(0, m.start() - 30):m.start()]) or NEGATED_AFTER.search(text[m.end():]):
            continue
        if NEAR_TARGET.search(text[max(0, m.start() - 60):m.end() + 60]):
            return True
    return False


def refuses_realtors(text):
    """True — автор прямо пише, що не співпрацює з рієлторами, і жодної співпраці не згадує."""
    text = re.sub(r"\s+", " ", str(text or ""))
    return bool(REFUSAL.search(text)) and not mentions_cooperation(text)
